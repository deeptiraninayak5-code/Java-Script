// String Properties & Basic Access

let str = "Hello, World!"
// length (start from 1)
console.log(str.length) //13

// Access by index
console.log(str[0]) // H
console.log(str[7]) // W
console.log(str.at(-1)) // !
console.log(str.at(-6)) // W

//  charAt()
str.charAt(0) // H

//  charCodeAt() - Unicode value
str.charCodeAt(0) // 72